DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "branch.svg")


def build(bg_color, ink_color, out_path):
    parts = []
    parts.append(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">')
    if bg_color is not None:
        parts.append(f'<rect width="{W}" height="{H}" fill="{bg_color}"/>')
    parts.append("\n".join(
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" '
        f'stroke="{ink_color}" stroke-width="{STROKE}" stroke-linecap="round"/>'
        for (x1, y1, x2, y2) in STROKES))
    parts.append('</svg>')
    with open(out_path, "w") as f:
        f.write("\n".join(parts) + "\n")
    bg_desc = bg_color if bg_color is not None else "transparent"
    print(f"wrote {out_path} (background: {bg_desc}, ink: {ink_color})")


def main():
    ap = argparse.ArgumentParser(description="Generate branch.svg")
    ap.add_argument("--bg", nargs="?", const="none", default="#F4F1EA",
                    help='background color (any CSS color, e.g. "#1e1e2e"; "none" = transparent)')
    ap.add_argument("--ink", default=INK,
                    help='branch/needle color (any CSS color, e.g. "#7aa2f7"; default: original dark ink)')
    ap.add_argument("-o", "--output", default=DEFAULT_OUT, help=f"output path (default: {DEFAULT_OUT})")
    args = ap.parse_args()
    bg = None if args.bg.strip().lower() in ("none", "transparent", "") else args.bg
    build(bg, args.ink, args.output)


if __name__ == "__main__":
    main()
